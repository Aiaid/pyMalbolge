"""Regenerate `debugger.dev.fixtures.js` from real `build_snapshot()` output.

The self-test page for canvas 1a must be driven by data the backend actually
produces, not by hand-written JSON -- the whole point of the exercise is to
find out what the renderer does with real numbers (a heat window whose maximum
is 5,883 and whose second-hottest cell is 3; a `seekable` lower bound of
11,500; an output long enough that `output_tail` is genuinely clipped).

Run from the repo root:

    uv run --no-sync python web/screens/debugger.dev.fixtures.py \\
        > web/screens/debugger.dev.fixtures.js
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)
os.chdir(ROOT)

from malbolge.debugger import MalbolgeDebugger          # noqa: E402
from malbolge.view import build_snapshot                # noqa: E402

# 24 x 12 heat map + the canvas's 16-row listing.
SNAP = dict(mem_count=288, disasm_count=16)
OUT = {}
src_truth = open("examples/truth.mal").read()

# --- paused: 400 steps in, one conditional breakpoint ------------------------
d = MalbolgeDebugger(src_truth, "hello")
for _ in range(400):
    d.step()
d.add_breakpoint(41, condition_text="a == 72")
OUT["paused"] = build_snapshot(d, **SNAP)

# --- crazy / rotate: the two shapes `teaching.ternary` can take --------------
for name, target in (("crazy", "crz"), ("rotate", "rotr")):
    dd = MalbolgeDebugger(src_truth, "hello")
    while dd.preview_next_instruction()["opcode_name"] != target or dd.step_count < 3000:
        dd.step()
    OUT[name] = build_snapshot(dd, **SNAP)

# --- deep: past the 10,000-step history window, so seekable[0] > 0 -----------
# This is the fixture the timeline's unreachable region exists for.
probe = MalbolgeDebugger(src_truth, "hello")
for _ in range(20000):
    probe.step()
hot = probe.get_state().c

deep = MalbolgeDebugger(src_truth, "hello")
deep.add_breakpoint(hot)                       # hot enough to accumulate hits
deep.add_breakpoint(41, condition_text="a == 72")
deep.toggle_breakpoint(41)                     # -> disabled, for the dimmed row
deep.add_breakpoint(102, temporary=True)
deep.add_watchpoint(hot + 7)
while deep.step_count < 20000 and not deep.is_terminated:
    deep.run(max_steps=20000 - deep.step_count)
for _ in range(1500):
    deep.step()
OUT["deep"] = build_snapshot(deep, **SNAP)

# --- truncated: output past OUTPUT_TAIL_CHARS, so output_truncated is True --
# The output panel has to say how much it is not showing; that branch needs a
# fixture where `output_len` and `len(output_tail)` genuinely disagree.
long = MalbolgeDebugger(src_truth, "hello")
while len(long.output) <= 5000 and not long.is_terminated:
    long.run(max_steps=5000)
OUT["truncated"] = build_snapshot(long, **SNAP)

# --- terminated: hello.mal run to the end -----------------------------------
done = MalbolgeDebugger(open("examples/hello.mal").read(), "")
done.run()
OUT["terminated"] = build_snapshot(done, **SNAP)

for k, v in OUT.items():
    tl, r = v["timeline"], v["registers"]
    print("%-11s step=%-7d seekable=%-16s max=%-7d out=%-5d trunc=%-5s ternary=%s" % (
        k, r["step"], tl["seekable"], tl["max_reached"], r["output_len"],
        r.get("output_truncated"),
        (v["teaching"].get("ternary") or {}).get("kind")), file=sys.stderr)

body = ",\n".join("  %s: %s" % (json.dumps(k), json.dumps(v, ensure_ascii=False))
                  for k, v in OUT.items())
print("// Generated by web/screens/debugger.dev.fixtures.py from real")
print("// malbolge.view.build_snapshot() output. Do not hand-edit.")
print("export const FIXTURES = {\n%s\n};" % body)
